import os
import openai

def fallback_heuristic_analysis(ticker: str, signals: dict, fundamental: dict, language: str = "zh") -> str:
    """
    當無提供 API Key 或網絡請求失敗時的啟發式規則專家報告生成器 (支援 zh / en)
    """
    company_name = fundamental.get("company_name", ticker)
    pe = fundamental.get("trailing_pe")
    pe_eval = signals.get("pe_evaluation", "無數據")
    macd_sig = signals.get("macd_signal", "觀望")
    macd_reason = signals.get("macd_reason", "指標趨勢不明顯")
    final_verdict = signals.get("final_verdict", "觀望")
    latest_close = signals.get("latest_close", 0.0)
    currency = fundamental.get("currency", "USD")

    if language == "en":
        report = f"""### 📊 {ticker} ({company_name}) Quantitative Strategy Analysis Report (Expert Rule Engine)

**Current Price**: {latest_close:.2f} {currency}  
**System Recommendation**: **{final_verdict}**

---

#### 1. Technical Momentum Diagnosis (MACD)
- **Latest Reading**: MACD line: `{signals.get('latest_macd', 0):.3f}` | Signal line: `{signals.get('latest_signal', 0):.3f}` | Histogram: `{signals.get('latest_hist', 0):.3f}`
- **Signal Interpretation**: **{macd_sig}**
- **Momentum Analysis**: {macd_reason} A widening histogram indicates strengthening momentum in that direction, while convergence warns of a potential trend reversal.

#### 2. Fundamental Valuation (P/E Ratio)
- **Trailing P/E**: {f"{pe:.2f}" if pe else "N/A"}
- **Valuation Assessment**: **{pe_eval}**
- **Value Analysis**: The P/E ratio reflects the market's expectation of the asset's future earnings growth. An excessively high ratio may imply valuation froth, whereas a very low one may reflect industry growth ceilings or underlying fundamental concerns.

#### 3. Actionable Strategy & Risk Warnings
- **Suggested Action**: Given the current overall signal of "**{final_verdict}**", investors should manage their position sizes prudently.
- **Stop-loss / Risk Control**: If entering a position, consider placing the stop-loss near the recent swing low (roughly 5% - 8% below the current price) and avoid chasing rallies during broad market turbulence.
- **Risk Disclaimer**: This report is auto-generated by a quantitative rule engine and is for reference only. It does not constitute any offer or guarantee of investment decisions.
"""
    else:
        report = f"""### 📊 {ticker} ({company_name}) 專業量化策略分析報告 (專家規則引擎)

**現價**: {latest_close:.2f} {currency}  
**系統綜合建議**: **{final_verdict}**

---

#### 1. 技術面動能診斷 (MACD 指標)
- **最新狀態**: MACD 線: `{signals.get('latest_macd', 0):.3f}` | 信號線: `{signals.get('latest_signal', 0):.3f}` | 柱狀圖: `{signals.get('latest_hist', 0):.3f}`
- **訊號解讀**: **{macd_sig}**
- **動能分析**: {macd_reason}。當 MACD 柱狀圖持續擴大時，代表該方向動能強勁；若出現收斂則需提防趨勢反轉。

#### 2. 基本面估值判斷 (P/E Ratio)
- **滾動市盈率 (Trailing P/E)**: {f"{pe:.2f}" if pe else "N/A"}
- **估值評估**: **{pe_eval}**
- **價值分析**: 市盈率反映市場對該資產未來盈利增長的預期。過高可能存在估值透支風險，過低則可能受限於行業增長瓶頸或基本面隱憂。

#### 3. 具體操作策略與風險提示
- **建議操作**: 鑑於目前的綜合訊號為「**{final_verdict}**」，投資者宜審慎管理倉位。
- **止蝕/風控指引**: 若決定建倉，建議將止蝕位設定在近期波段低位（約現價下方 5% - 8% 區間），並避免於大市震盪時盲目追高。
- **風險提示**: 本報告由量化規則自動生成，僅供參考，不構成任何要約或投資決策保證。
"""
    return report


def _build_candidate_configs() -> list[dict]:
    """
    生成多組 (base_url, models) 候選組合，用於解決 NotFoundError (HTTP 404)。
    404 通常由於：
      (1) OPENAI_BASE_URL 路徑格式不符（例如多了或少了 /v1 後綴）；
      (2) 該 API Key 所屬帳戶沒有指定模型（如 gpt-3.5-turbo）的存取權限。
    """
    custom_base = (os.environ.get("OPENAI_BASE_URL") or os.environ.get("OPENAI_API_BASE") or "").strip()
    env_model = (os.environ.get("OPENAI_MODEL") or os.environ.get("OPENAI_API_MODEL") or "").strip()

    # 模型候選清單：環境變量指定的模型優先，其後為通用備選
    models = [m for m in (env_model, "gpt-3.5-turbo", "gpt-4o-mini") if m]

    candidates = []
    if custom_base:
        base = custom_base.rstrip("/")
        # 1) 先按用戶原設定嘗試（不少第三方代理不需要 /v1 後綴）
        candidates.append({"base_url": base, "models": models})
        # 2) 若原設定失敗，補上 /v1 再試（官方及多數代理的格式）
        if not base.endswith("/v1"):
            candidates.append({"base_url": base + "/v1", "models": models})
    # 3) 最後一律退回官方端點，避免環境變量設錯導致永遠失敗
    candidates.append({"base_url": None, "models": models})
    return candidates


def generate_ai_analysis(ticker: str, signals: dict, fundamental: dict, openai_api_key: str = None, language: str = "zh") -> str:
    """
    調用 LLM 生成深度投資診斷，加入嚴格超時與代理錯誤防禦，確保絕不卡死 (支援 zh / en)

    針對 NotFoundError (HTTP 404) 的防禦：
    - 依序嘗試多組 (base_url, model) 組合：用戶原設定 → 補上 /v1 → 官方端點；
    - 模型名稱可透過環境變量 OPENAI_MODEL 指定，否則依序嘗試 gpt-3.5-turbo 及 gpt-4o-mini。
    """
    clean_key = str(openai_api_key).strip() if openai_api_key else ""
    # 若 API Key 未提供，直接使用本地規則引擎，不發出任何網絡請求
    # （放寬原本強制 sk- 開頭的檢查，以兼容第三方代理服務的金鑰格式）
    if not clean_key:
        return fallback_heuristic_analysis(ticker, signals, fundamental, language=language)

    if language == "en":
        prompt_context = f"""
Ticker: {ticker} ({fundamental.get('company_name', 'N/A')})
Sector: {fundamental.get('sector', 'N/A')}
Latest close: {signals.get('latest_close', 0):.2f} {fundamental.get('currency', 'USD')}
P/E ratio: {fundamental.get('trailing_pe')}
P/E assessment: {signals.get('pe_evaluation')}
MACD status: MACD={signals.get('latest_macd', 0):.3f}, Signal={signals.get('latest_signal', 0):.3f}, Histogram={signals.get('latest_hist', 0):.3f}
MACD trend: {signals.get('macd_signal')} ({signals.get('macd_reason')})
Overall strategy verdict: {signals.get('final_verdict')}
"""
        system_prompt = (
            "You are a senior CFA charterholder working at a financial institution in Hong Kong. "
            "Your task is to explain the strategy signals of this stock to an investor. "
            "Please write the report in English, covering: "
            "1. Technical and momentum analysis (interpret the MACD signal and any divergence); "
            "2. Fundamental valuation (assess whether the P/E ratio is reasonable); "
            "3. Actionable strategy (buy, wait, or stop-loss level suggestions); "
            "4. Risk warnings for retail investors. "
            "Keep the tone professional, objective, clear and practical."
        )
        user_prompt = f"Please generate an investment diagnostic report based on the following quantitative data:\n{prompt_context}"
    else:
        prompt_context = f"""
股票代號: {ticker} ({fundamental.get('company_name', 'N/A')})
板塊: {fundamental.get('sector', 'N/A')}
最新收盤價: {signals.get('latest_close', 0):.2f} {fundamental.get('currency', 'USD')}
P/E (市盈率): {fundamental.get('trailing_pe')}
P/E 評估: {signals.get('pe_evaluation')}
MACD 現況: MACD={signals.get('latest_macd', 0):.3f}, Signal={signals.get('latest_signal', 0):.3f}, 柱狀圖={signals.get('latest_hist', 0):.3f}
MACD 趨勢判斷: {signals.get('macd_signal')} ({signals.get('macd_reason')})
系統綜合策略結論: {signals.get('final_verdict')}
"""
        system_prompt = (
            "你是一位在香港金融機構工作的資深特許金融分析師（CFA）。"
            "你的任務是向投資者解釋這隻股票的策略訊號。"
            "請使用繁體中文（香港慣用語法），包含："
            "1. 技術面與動能分析（解讀 MACD 訊號及背離狀況）；"
            "2. 基本面估值判斷（分析市盈率 P/E 是否合理）；"
            "3. 具體操作策略（買入、觀望或止蝕點位建議）；"
            "4. 針對個人投資者的風險提示。"
            "風格需保持專業、客觀、清晰且具實操性。"
        )
        user_prompt = f"請根據以下量化數據生成一份投資診斷報告：\n{prompt_context}"

    try:
        # 若環境中存在 litellm 全域變量，設定保護防止背景無窮重試
        try:
            import litellm
            litellm.num_retries = 0
            litellm.request_timeout = 4.0
            litellm.drop_params = True
        except ImportError:
            pass

        # 讀取超時設定（預設 20 秒；原本 4 秒對 LLM 生成而言過短，容易誤報失敗）
        try:
            timeout = float(os.environ.get("OPENAI_TIMEOUT", "20"))
        except (TypeError, ValueError):
            timeout = 20.0
        if timeout <= 0:
            timeout = 20.0

        last_error = None
        hard_fail = False

        for cfg in _build_candidate_configs():
            client_kwargs = {
                "api_key": clean_key,
                "timeout": timeout,   # 硬性超時限制，防止連線掛起
                "max_retries": 0      # 嚴格禁止重試，防止反覆嘗試被阻擋的網絡端點
            }
            if cfg["base_url"]:
                client_kwargs["base_url"] = cfg["base_url"]

            client = openai.OpenAI(**client_kwargs)

            for model in cfg["models"]:
                try:
                    response = client.chat.completions.create(
                        model=model,
                        messages=[
                            {"role": "system", "content": system_prompt},
                            {"role": "user", "content": user_prompt}
                        ],
                        temperature=0.3,
                        max_tokens=700
                    )
                    content = response.choices[0].message.content
                    if not content or "<!DOCTYPE html>" in content:
                        raise ValueError("收到無效的 HTML 響應")
                    return content
                except (openai.AuthenticationError, openai.PermissionDeniedError) as e:
                    # 金鑰無效或無權限：重試其他端點/模型亦無幫助，直接終止所有嘗試
                    last_error = e
                    hard_fail = True
                    break
                except openai.NotFoundError as e:
                    # HTTP 404：模型不存在或端點路徑不符 → 換下一個模型 / 端點再試
                    last_error = e
                    continue
                except Exception as e:
                    # 連線逾時或其他錯誤 → 換下一個端點再試（同一端點換模型無幫助）
                    last_error = e
                    break
            if hard_fail:
                break

        # 所有候選組合均失敗，拋出最後一次的錯誤以觸發 fallback
        raise last_error if last_error is not None else RuntimeError("AI 請求全部失敗")

    except BaseException as e:
        # 完全攔截所有異常（包含 litellm.APIError / HTML 報錯 / 連線逾時），自動切換至專家規則引擎
        not_found_cls = getattr(openai, "NotFoundError", ())
        if isinstance(e, not_found_cls):
            if language == "en":
                extra_hint = " (Hint: HTTP 404 usually means this API key has no access to the model, or OPENAI_BASE_URL path is malformed. You can set OPENAI_MODEL in Streamlit Secrets to force an available model.)"
            else:
                extra_hint = "（小提示：404 通常表示此 API Key 無權使用該模型，或 OPENAI_BASE_URL 路徑格式有誤；可在 Streamlit Secrets 設定 OPENAI_MODEL 指定可用模型。）"
        else:
            extra_hint = ""

        if language == "en":
            error_notice = f"(Note: online AI API connection unavailable [{type(e).__name__}]; automatically switched to the quantitative expert rule engine){extra_hint}\n\n"
        else:
            error_notice = f"（提示：AI 線上 API 連線受限 [{type(e).__name__}]，已自動切換至量化專家系統生成報告）{extra_hint}\n\n"
        return error_notice + fallback_heuristic_analysis(ticker, signals, fundamental, language=language)
